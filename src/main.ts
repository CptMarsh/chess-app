import { StockfishEngine } from "./engine/engine.ts";
import { ChessComExplorer } from "./explorer/chessCom.ts";
import { LichessExplorer } from "./explorer/explorer.ts";
import { SourceExplorer } from "./explorer/source.ts";
import { attachLine } from "./line/line.ts";
import { LineBus } from "./line/messages.ts";
import { SettingsStore } from "./settings/settings.ts";
import captureSound from "./sound/capture.wav?url";
import moveSound from "./sound/move.wav?url";
import { PieceSounds } from "./sound/sound.ts";
import { TokenStore } from "./token/token.ts";
import { Trainer } from "./trainer/trainer.ts";
import { mountTokenDialog } from "./ui/tokenView.ts";
import { mountTrainer } from "./ui/trainerView.ts";

const bus = new LineBus();
attachLine(bus);
const engine = new StockfishEngine(new Worker(`${import.meta.env.BASE_URL}stockfish/stockfish-19-lite-single.js`));
const tokens = new TokenStore(() => localStorage);
const settings = new SettingsStore(() => localStorage);
const explorer = new SourceExplorer(() => settings.source(), new LichessExplorer(() => tokens.read()), new ChessComExplorer(() => settings.username()));
const view = { show: () => {} };
const trainer = new Trainer(bus, engine, explorer, () => view.show());
const askToken = mountTokenDialog(document.body, tokens);
view.show = mountTrainer(document.querySelector<HTMLElement>("#app")!, bus, trainer, askToken, settings, new PieceSounds({ move: moveSound, capture: captureSound }));
view.show();
if (settings.source() === "lichess" && tokens.read() === "") askToken();
